/* Electric Pro V29 — сопоставление названий позиций с записями базы.
   ЕДИНЫЙ источник для двух мест, которые раньше держали свои копии и УЖЕ разошлись:
   · plan-calc.js priceFor()  — автоподстановка цены в «Расчёте» проекта квартиры;
   · pick-and-estimate.js     — поиск и автоподбор в «Карточке позиции».
   Расхождение было не теоретическим: cardNorm чистил пунктуацию, priceNorm — нет,
   и «Кабель ВВГнг(А)-LS 3×2.5» превращался в две разные строки — карточка запись
   находила, а цена в смете к ней не подтягивалась.

   Модуль подключается ПЕРВЫМ в блоке сметы (раньше pick-and-estimate.js и plan-calc.js),
   оба зовут его через window.EP.NameMatch со своим фолбэком на случай, если файл
   не подключён на странице. */
(function () {
  "use strict";
  const EP = (window.EP = window.EP || {});

  /* Нормализация имени. Приложение пишет сечение «3×2.5», накладная поставщика — то же
     самое «3х2,5» (латинская/кириллическая х против ×, запятая против точки); скобки и
     дефисы в «ВВГнг(А)-LS» у разных поставщиков стоят по-разному. Приводим к общему виду,
     иначе физически одинаковые позиции не совпадают ни точно, ни подстрокой. */
  function norm(s) {
    return String(s == null ? "" : s).toLowerCase()
      .replace(/ё/g, "е")
      .replace(/[×хx*]/g, "x")          // 3×2.5 / 3х2,5 / 3x2,5 / 3*2,5 — одно и то же
      .replace(/(\d),(\d)/g, "$1.$2")   // десятичная запятая → точка
      .replace(/[^0-9a-zа-я.]+/g, " ")  // скобки, дефисы, слеши — разделители
      .replace(/\s+/g, " ").trim();
  }

  /* Выбор записи базы под данное название.
     Точное совпадение выигрывает всегда. Дальше — подстрока В ОБЕ СТОРОНЫ, но
     СРЕДИ ВСЕХ совпавших берётся САМОЕ ТОЧНОЕ, а не первое попавшееся, как было раньше.
     Тот старый «первый find» давал реальную ошибку в деньгах: короткая родовая запись
     мастера («Штробление» 120 ₽) перехватывала цену у специфичной позиции
     («Штробление 25x30 бетон» 450 ₽) просто потому, что лежала в базе выше.

     Мера точности — длина РЕАЛЬНО совпавшей части, то есть длина более короткой строки
     из пары: у «штробление 25x30 бетон» ⊂ запроса она 22, у «штробление» — 10, значит
     выигрывает первая. При равной мере предпочитаем запись, чья длина ближе к запросу
     (меньше лишнего хвоста) — так «Кабель ВВГ 3x2.5» бьёт «Кабель ВВГ 3x2.5 ГОСТ бухта 100м». */
  function best(name, items, getName) {
    const list = items || [];
    const nameOf = getName || ((x) => (x && x.name) || "");
    const low = norm(name);
    if (!low) return null;
    let hit = null, hitScore = -1, hitGap = Infinity;
    for (let i = 0; i < list.length; i++) {
      const n = norm(nameOf(list[i]));
      if (!n) continue;
      if (n === low) return list[i];                     // точное — дальше не ищем
      const inside = low.indexOf(n) >= 0 || n.indexOf(low) >= 0;
      if (!inside) continue;
      const score = Math.min(n.length, low.length);      // сколько реально совпало
      const gap = Math.abs(n.length - low.length);       // сколько лишнего сверх совпадения
      if (score > hitScore || (score === hitScore && gap < hitGap)) {
        hit = list[i]; hitScore = score; hitGap = gap;
      }
    }
    return hit;
  }

  EP.NameMatch = { norm, best };
})();
